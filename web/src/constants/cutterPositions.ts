export const CUTTER_POSITIONS: CutterPosition[] = RAW_CUTTER_POSITIONS.map(position => {
  const override = FINAL_POSITION_OVERRIDES[position.code.toUpperCase()];
  if (override) return { ...position, ...override };

  return {
    ...position,
    x: Math.round(CUTTERHEAD_IMAGE_CENTER.x + (position.x - LEGACY_IMAGE_CENTER.x) * FINAL_IMAGE_SCALE),
    y: Math.round(CUTTERHEAD_IMAGE_CENTER.y + (position.y - LEGACY_IMAGE_CENTER.y) * FINAL_IMAGE_SCALE),
  };
});

const ACTIVE_CUTTER_POSITION_CODES = new Set([
  ...Array.from({ length: 79 }, (_, index) => String(index + 1)),
  '80a',
  '80b',
  'y1',
  'y3',
  'y5',
  ...Array.from({ length: 19 }, (_, index) => `S${index + 1}L`),
  ...Array.from({ length: 19 }, (_, index) => `S${index + 1}R`),
].map(code => code.toUpperCase()));

export const isActiveCutterPosition = (code?: string | null) => {
  return !!code && ACTIVE_CUTTER_POSITION_CODES.has(code.toUpperCase());
};

export const ACTIVE_CUTTER_POSITIONS: CutterPosition[] = CUTTER_POSITIONS.filter(pos =>
  isActiveCutterPosition(pos.code)
);

export const ACTIVE_LEGACY_CUTTER_POSITIONS: CutterPosition[] = LEGACY_CUTTER_POSITIONS.filter(pos =>
  isActiveCutterPosition(pos.code)
);
